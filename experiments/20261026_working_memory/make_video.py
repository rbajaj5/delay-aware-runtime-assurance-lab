def rings(t):
    u=(t-36)/18;rnd=min(179,int(u*180));phase=(u*180)%1
    im,d=base(t,'04 / MATCHED REPLAY','Same world. Different remembered state.',f'Round {rnd+1:03d} / 180    ·    seed 20261026    ·    accelerated trace replay')
    for k,p in enumerate(POLICIES):
        x=60+k*625;cx=x+288;cy=470;rad=155;s=TRACE[p][rnd]
        box(d,(x,236,x+600,880));txt(d,(cx,255),LABELS[k],31,COLORS[k],True,anchor='ma')
        pts=[(cx+rad*math.sin(i*math.tau/12),cy-rad*math.cos(i*math.tau/12)) for i in range(12)]
        for i in range(12):d.line([pts[i],pts[(i+1)%12]],fill=LINE,width=3)
        for rec,served in enumerate(s['served']):
            for msg in served:
                if not msg['useful']:continue
                a=pts[msg['sender']];b=pts[rec];q=(a[0]+(b[0]-a[0])*phase,a[1]+(b[1]-a[1])*phase)
                d.ellipse([q[0]-4,q[1]-4,q[0]+4,q[1]+4],fill=COLORS[k])
        for i,(px,py) in enumerate(pts):
            bad=any(s['memory'][i].get(str(j))!=s['truth'][j] for j in ((i-1)%12,(i+1)%12))
            d.ellipse([px-23,py-23,px+23,py+23],fill='#203b4c',outline=CORAL if bad else CYAN,width=4 if bad else 2)
            txt(d,(px,py-1),'+' if s['truth'][i]>0 else '−',23,INK,True,anchor='mm')
        txt(d,(cx,438),f"{100*s['stale_total']/s['decisions']:.1f}%",46,COLORS[k],True,anchor='ma')
        txt(d,(cx,498),'mismatch so far',23,MUTED,anchor='ma')
        txt(d,(x+25,653),'AGENT 00 / LOCAL MEMORY',21,GOLD,True)
        for jj,j in enumerate((11,1)):
            val=s['memory'][0].get(str(j));created=s['memory_created'][0].get(str(j))
            text=f'A{j:02d}:  truth {s["truth"][j]:+d}   memory {val:+d}' if val is not None else f'A{j:02d}:  truth {s["truth"][j]:+d}   memory ?'
