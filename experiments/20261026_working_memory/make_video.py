def render():
    cmd=[FF,'-v','error','-y','-f','rawvideo','-pix_fmt','rgb24','-s',f'{W}x{H}','-r',str(FPS),'-i','-',
         '-an','-c:v','libx264','-preset','fast','-crf','20','-pix_fmt','yuv420p','-movflags','+faststart',str(B/'silent.mp4')]
    p=subprocess.Popen(cmd,stdin=subprocess.PIPE)
    try:
        for i in range(FPS*LENGTH):
            p.stdin.write(frame(i/FPS).tobytes())
            if i%(FPS*10)==0:print(f'Rendered {i//FPS:03d}/{LENGTH}s',flush=True)
    finally:p.stdin.close()
    if p.wait():raise RuntimeError('Video encoder failed')

def mux():
    audio=np.zeros(48000*LENGTH,dtype=np.float64);audit=[]
    for i,(start,end,text) in enumerate(SEGMENTS):
        path=B/f'voice_{i:02d}.wav'
        with wave.open(str(path),'rb') as w:duration=w.getnframes()/w.getframerate()
        available=end-start-.6;speed=max(1.,duration/available)
        assert speed<1.6, f'Narration too dense in segment {i}'
        out=B/f'voice_fit_{i:02d}.wav'
        subprocess.run([FF,'-v','error','-y','-i',str(path),'-af',f'atempo={speed:.6f}',
                        '-ar','48000','-ac','1','-c:a','pcm_s16le',str(out)],check=True)
        with wave.open(str(out),'rb') as w:samples=np.frombuffer(w.readframes(w.getnframes()),dtype=np.int16).astype(float)
        off=round((start+.2)*48000);assert off+len(samples)<end*48000
        audio[off:off+len(samples)]+=samples
        audit.append(dict(segment=i,original_duration=duration,speed=speed,window=end-start,rendered_duration=len(samples)/48000))
    peak=np.max(np.abs(audio));audio*=min(1.8,29000/max(peak,1))
    with wave.open(str(B/'narration.wav'),'wb') as w:
        w.setnchannels(1);w.setsampwidth(2);w.setframerate(48000);w.writeframes(audio.astype(np.int16).tobytes())
    subprocess.run([FF,'-v','error','-y','-i',str(B/'silent.mp4'),'-i',str(B/'narration.wav'),
                    '-i',str(D/'Working_Memory_Captions.srt'),'-map','0:v','-map','1:a','-map','2:s',
                    '-c:v','copy','-c:a','aac','-b:a','160k','-c:s','mov_text',
                    '-metadata:s:a:0','language=eng','-metadata:s:s:0','language=eng',
                    '-metadata','title=Working Memory | Queue-aware Assured Autonomy',
                    '-movflags','+faststart',str(D/'Working_Memory_Assured_Autonomy.mp4')],check=True)
    (E/'audio_validation.json').write_text(json.dumps(dict(segments=audit,peak_pcm16=float(np.max(np.abs(audio))),rms_pcm16=float(np.sqrt(np.mean(audio**2)))),indent=2))

