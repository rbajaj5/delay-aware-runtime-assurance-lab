def font(size,bold=False,chinese=False):
    f='msyh.ttc' if chinese else ('seguisb.ttf' if bold else 'segoeui.ttf')
    return ImageFont.truetype(str(Path('C:/Windows/Fonts')/f),size)

def txt(d,xy,s,size=30,color=INK,bold=False,chinese=False,anchor=None):
    chinese=chinese or any('\u4e00'<=c<='\u9fff' for c in str(s))
    d.text(xy,str(s),font=font(size,bold,chinese),fill=color,anchor=anchor)

def wrap(d,s,width,size=30):
    lines=[];line=''
    for w in s.split():
        nxt=(line+' '+w).strip()
        if d.textlength(nxt,font=font(size,chinese=any('\u4e00'<=c<='\u9fff' for c in nxt)))>width and line:lines.append(line);line=w
        else:line=nxt
    if line:lines.append(line)
    return lines

def para(d,xy,s,width=800,size=30,color=INK,gap=10,bold=False):
    x,y=xy
    for line in wrap(d,s,width,size):
        txt(d,(x,y),line,size,color,bold);y+=size+gap
    return y

def box(d,rect,fill=PANEL,outline=LINE,r=20,width=1):
    d.rounded_rectangle(rect,radius=r,fill=fill,outline=outline,width=width)

def arrow(d,a,b,color=CYAN,width=4):
    d.line([a,b],fill=color,width=width)
    ang=math.atan2(b[1]-a[1],b[0]-a[0]);l=15
    d.polygon([b,(b[0]-l*math.cos(ang-.5),b[1]-l*math.sin(ang-.5)),
               (b[0]-l*math.cos(ang+.5),b[1]-l*math.sin(ang+.5))],fill=color)

def ease(x):return .5-.5*math.cos(math.pi*max(0,min(1,x)))

